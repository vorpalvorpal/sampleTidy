# Regenerates feature-names.csv: a SYNTHETIC stand-in for a registry
# feature.name snapshot (R-11.3 frozen-snapshot test in test-reconcile.R).
# Inputs are synthetic only: the family table below and a fixed seed.
# Run from anywhere: Rscript generate-feature-names.R
#
# Shape it reproduces: 928 distinct upper-case names under the shared
# synthetic-site convention (N, M, P and NH prefixes) in the families a real
# registry has: 3-digit and 2-digit gas points (G), monitoring wells (MW) with
# A/B/C suffix variants, surface and sediment points (S, TS, TG, TMW, L, E,
# D, CW, WS) and one lower-case "centroid" per site. Padding widths differ
# between families on purpose (2 digits vs 3 digits, and both within G).
# No two names collide under the lower-case fold (distinct_keys == rows).

script_dir <- function() {
  a <- grep("^--file=", commandArgs(FALSE), value = TRUE)
  if (length(a)) dirname(normalizePath(sub("^--file=", "", a[[1]]))) else getwd()
}

set.seed(20261105)

# site prefix, family, digit width, how many, number range, suffixes (if any)
fam <- function(site, family, width, n, lo, hi, suffix = "") {
  list(site = site, family = family, width = width, n = n, lo = lo, hi = hi,
       suffix = suffix)
}
spec <- list(
  fam("N",  "G",   3, 380, 101, 640),
  fam("N",  "TS",  2,  27,   1,  60),
  fam("N",  "TG",  3,  24, 101, 260),
  fam("N",  "S",   2,  16,   1,  45),
  fam("N",  "MW",  2,  11,   1,  30),
  fam("N",  "L",   2,   5,   1,  12),
  fam("N",  "TMW", 2,   4,   1,  15),
  fam("N",  "D",   2,   2,   3,  19),
  fam("N",  "CW",  2,   2,   1,   9),
  fam("N",  "E",   2,   1,   1,  20),
  fam("N",  "WS",  2,   1,   1,   9),
  fam("M",  "G",   3, 351, 120, 700),
  fam("M",  "G",   2,  21,   2,  80),
  fam("M",  "MW",  2,  10,   1,  25),
  fam("M",  "S",   2,   7,   1,  30),
  fam("M",  "TS",  2,   6,   1,  20),
  fam("M",  "L",   2,   6,   1,  20),
  fam("M",  "E",   2,   2,   1,  12),
  fam("M",  "WS",  2,   1,   1,   9),
  fam("P",  "G",   2,  25,   1,  60),
  fam("P",  "MW",  2,   4,   1,  12),
  fam("P",  "S",   2,   2,   1,  10),
  fam("P",  "L",   2,   2,   1,  10),
  fam("NH", "MW",  2,   5,   1,  15),
  fam("NH", "S",   2,   3,   1,  10)
)
# suffix variants: one number per suffix, on top of the counts above
suffixed <- list(
  list(site = "N",  family = "MW", suffixes = character(0)),
  list(site = "M",  family = "MW", suffixes = c("A", "B")),
  list(site = "M",  family = "S",  suffixes = "A"),
  list(site = "NH", family = "MW", suffixes = c("A", "B", "C"))
)

pad <- function(n, w) formatC(n, width = w, flag = "0")
out <- character(0)
for (s in spec) {
  nums <- sort(sample(s$lo:s$hi, s$n))
  out <- c(out, paste0(s$site, ".", s$family, pad(nums, s$width)))
}
for (s in suffixed) {
  for (sx in s$suffixes) {
    # a number not already used as a plain name in this family
    repeat {
      k <- sample(31:49, 1)
      base <- paste0(s$site, ".", s$family, pad(k, 2))
      if (!(base %in% out)) break
    }
    out <- c(out, paste0(base, sx))
  }
}
out <- c(out, paste0(c("N", "M", "P", "NH"), ".centroid"))

stopifnot(!anyDuplicated(tolower(out)))
# The suffixed rows count towards the 928 total: drop plain rows to compensate.
extra <- length(out) - 928L
if (extra > 0L) {
  drop <- sample(grep("^N\\.G", out), extra)
  out <- out[-drop]
}
stopifnot(length(out) == 928L)

# order: site, family, then number, with "centroid" first in its site
site <- sub("\\..*$", "", out)
rest <- sub("^[A-Z]+\\.", "", out)
key <- order(factor(site, c("N", "NH", "M", "P")), rest != "centroid",
             sub("[0-9]+[A-Z]?$", "", rest), suppressWarnings(as.integer(sub("^[A-Za-z]+([0-9]+).*$", "\\1", rest))),
             rest)
out <- out[key]

hdr <- c(
  "# R-11.3 frozen snapshot: SYNTHETIC feature.name values shaped like a registry",
  "# snapshot (generated by generate-feature-names.R, fixed seed). Names only,",
  "# no other columns.",
  sprintf("# rows=%d distinct_keys=%d", length(out), length(unique(tolower(out)))),
  "\"name\""
)
writeLines(c(hdr, sprintf("\"%s\"", out)), file.path(script_dir(), "feature-names.csv"))
