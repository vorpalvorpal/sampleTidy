# ---- registry: behaviour change is signalled -------------------------------------
#
# R-3.8: router verdicts are re-decided only when the registry fingerprint
# (adapter ids + versions) changes, and "an adapter author signals a
# behaviour change by bumping `version`" (registry_fingerprint() doc). The
# live DB holds eight XTAB.XLS files quarantined `unclaimed` under
# als_xtab 1.0; unless the version moves they are never re-decided.

test_that("SpreadsheetML: als_xtab's version is bumped past 1.0 so previously-unclaimed .XLS files get re-routed", {
  expect_false(identical(as.character(xtab_adapter()$version), "1.0"))
})
