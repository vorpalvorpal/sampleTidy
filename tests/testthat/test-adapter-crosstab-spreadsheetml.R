# tests/testthat/test-adapter-crosstab-spreadsheetml.R
#
# `als_xtab` reads ALS's XTAB delivered as a SpreadsheetML 2003 XML ".XLS"
# (CONTRACT A37 un-parked, 2026-10-18). Required behaviour: such a file is
# matched and parsed by `als_xtab` exactly as its `XTAB.csv` twin is - the
# same grid of cell text, so the parse yields identical samples, analytes,
# values, units, LORs, "<" non-detects, dates and source_refs. `als_enmrg`
# never claims it; binary workbooks and CSVs are unchanged; a malformed or
# non-SpreadsheetML ".XLS" returns "no" without crashing.
#
# Fixtures:
#  - fixtures/crosstab/ES2600185_0_XTAB.{csv,XLS}: the REAL anonymised twin
#    pair (see fixtures/REAL-FIXTURES.md). The .XLS has two worksheets,
#    "Client WATER - 1" (= the .csv) and "QC WATER - 1" (QC lots plus other
#    clients' primary samples - not in the .csv, must not be ingested).
#  - fixtures/spreadsheetml/*: synthetic, generated by
#    fixtures/spreadsheetml/make-spreadsheetml.R (structure copied from the
#    real files, plus ss:Index cell/row gaps). Both twin grids were checked
#    cell-for-cell against an independent xml2 reader before these tests
#    were written (0 differences after trimws + normalise_lab_text).

xtab_adapter  <- function() sampleTidy:::adapter_registry()[["als_xtab"]]
enmrg_adapter <- function() sampleTidy:::adapter_registry()[["als_enmrg"]]

real_csv <- test_path("fixtures", "crosstab", "ES2600185_0_XTAB.csv")
real_xls <- test_path("fixtures", "crosstab", "ES2600185_0_XTAB.XLS")
sx_csv   <- test_path("fixtures", "spreadsheetml", "SX7654321_0_XTAB.csv")
sx_xls   <- test_path("fixtures", "spreadsheetml", "SX7654321_0_XTAB.XLS")

sx_truncated <- test_path("fixtures", "spreadsheetml", "SX0000001_0_XTAB.XLS")
sx_not_ssml  <- test_path("fixtures", "spreadsheetml", "SX0000002_0_XTAB.XLS")
sx_enmrg_ssml <- test_path("fixtures", "spreadsheetml", "SX0000003_0_XTAB.XLS")
sx_garbage   <- test_path("fixtures", "spreadsheetml", "SX0000004_0_XTAB.XLS")

parse_xtab <- function(path) {
  xtab_adapter()$parse(path, sampleTidy:::file_meta(path))
}

# source_hash is the file's content hash, so it legitimately differs between
# twins; every other column must be identical.
drop_hash <- function(df) {
  df$source_hash <- NULL
  df
}

expect_twin_parse_identical <- function(csv_path, xls_path) {
  from_csv <- parse_xtab(csv_path)
  from_xls <- parse_xtab(xls_path)

  expect_gt(nrow(from_csv$results), 0) # guard: empty == empty proves nothing
  expect_identical(drop_hash(from_xls$results), drop_hash(from_csv$results))
  expect_identical(drop_hash(from_xls$samples), drop_hash(from_csv$samples))
  expect_identical(from_xls$report$skipped, from_csv$report$skipped)
  expect_identical(from_xls$report$n_by_sample_type, from_csv$report$n_by_sample_type)
  # warnings may name the file; compare with the filename masked
  mask <- function(w, path) gsub(basename(path), "<file>", w, fixed = TRUE)
  expect_identical(mask(from_xls$report$warnings, xls_path),
                   mask(from_csv$report$warnings, csv_path))
}

# ---- match() -----------------------------------------------------------------

test_that("SpreadsheetML: real XTAB .XLS is claimed by als_xtab at format tier, never by als_enmrg", {
  meta <- sampleTidy:::file_meta(real_xls)
  expect_identical(xtab_adapter()$match(meta), "format")
  expect_identical(enmrg_adapter()$match(meta), "no")
})

test_that("SpreadsheetML: synthetic XTAB .XLS (ss:Index gaps) is claimed by als_xtab at format tier, never by als_enmrg", {
  meta <- sampleTidy:::file_meta(sx_xls)
  expect_identical(xtab_adapter()$match(meta), "format")
  expect_identical(enmrg_adapter()$match(meta), "no")
})

test_that("SpreadsheetML: the .csv twins are still claimed exactly as before", {
  for (p in c(real_csv, sx_csv)) {
    meta <- sampleTidy:::file_meta(p)
    expect_identical(xtab_adapter()$match(meta), "format", info = basename(p))
    expect_identical(enmrg_adapter()$match(meta), "no", info = basename(p))
  }
})

test_that("SpreadsheetML: a truncated (malformed XML) .XLS matches no from both adapters, without error", {
  meta <- sampleTidy:::file_meta(sx_truncated)
  expect_no_error(xt <- xtab_adapter()$match(meta))
  expect_no_error(en <- enmrg_adapter()$match(meta))
  expect_identical(xt, "no")
  expect_identical(en, "no")
})

test_that("SpreadsheetML: well-formed XML that is not SpreadsheetML matches no, even with Matrix:/Workgroup: text", {
  meta <- sampleTidy:::file_meta(sx_not_ssml)
  expect_no_error(xt <- xtab_adapter()$match(meta))
  expect_no_error(en <- enmrg_adapter()$match(meta))
  expect_identical(xt, "no")
  expect_identical(en, "no")
})

test_that("SpreadsheetML: a binary-garbage .XLS (neither XML nor BIFF) matches no, without error", {
  meta <- sampleTidy:::file_meta(sx_garbage)
  expect_no_error(xt <- xtab_adapter()$match(meta))
  expect_no_error(en <- enmrg_adapter()$match(meta))
  expect_identical(xt, "no")
  expect_identical(en, "no")
})

test_that("SpreadsheetML: a SpreadsheetML workbook whose first row is 'Client - Matrix:' is not claimed by als_xtab", {
  meta <- sampleTidy:::file_meta(sx_enmrg_ssml)
  expect_identical(xtab_adapter()$match(meta), "no")
  expect_no_error(enmrg_adapter()$match(meta))
})

test_that("SpreadsheetML: a genuine binary BIFF .xls still goes through readxl - no error, not claimed when not a crosstab", {
  biff <- system.file("extdata", "datasets.xls", package = "readxl")
  skip_if(!nzchar(biff), "readxl's datasets.xls example not installed")
  dir <- withr::local_tempdir()
  path <- file.path(dir, "XX1234567_0_XTAB.xls")
  file.copy(biff, path)
  meta <- sampleTidy:::file_meta(path)
  expect_no_error(xt <- xtab_adapter()$match(meta))
  expect_no_error(en <- enmrg_adapter()$match(meta))
  expect_identical(xt, "no")
  expect_identical(en, "no")
})

test_that("SpreadsheetML: the .xlsx crosstab twin still matches and parses via readxl, unchanged", {
  xlsx <- test_path("fixtures", "crosstab", "XX1234567_0_XTAB.xlsx")
  meta <- sampleTidy:::file_meta(xlsx)
  expect_identical(xtab_adapter()$match(meta), "format")
  out <- xtab_adapter()$parse(xlsx, meta)
  expect_equal(nrow(out$results), 3)
  expect_equal(nrow(out$samples), 3)
})

# ---- parse(): twin equality ----------------------------------------------------

test_that("SpreadsheetML: real ES2600185 .XLS parses identically to its .csv twin", {
  expect_twin_parse_identical(real_csv, real_xls)
})

test_that("SpreadsheetML: real ES2600185 .XLS - the documented .csv counts hold (54 results, 24 skips, 3 samples)", {
  out <- parse_xtab(real_xls)
  expect_equal(nrow(out$results), 54)
  expect_equal(length(unique(out$results$analyte_raw)), 26)
  expect_equal(nrow(out$report$skipped), 24)
  expect_true(all(out$report$skipped$reason == "not_computable"))
  expect_equal(nrow(out$samples), 3)
  expect_setequal(out$samples$lab_sample_id, c("ES2600185001", "ES2600185002", "ES2600185003"))
  expect_setequal(out$samples$feature_raw, c("P.S03", "P.S07", "P.S09"))
  expect_true(all(out$samples$sample_datetime_raw == "05/01/2026"))
  expect_true(all(out$results$adapter == out$samples$adapter[[1]]))
  expect_match(out$results$adapter[[1]], "^als_xtab/")
})

test_that("SpreadsheetML: the real .XLS's 'QC WATER - 1' worksheet is not ingested (no QC lots, no other clients' samples)", {
  out <- parse_xtab(real_xls)
  expect_false(any(grepl("^QC-", out$samples$lab_sample_id)))
  expect_false(any(grepl("^QC-", out$results$lab_sample_id)))
  # the QC sheet carries other work orders' primary samples, e.g. ES2600144001
  expect_true(all(grepl("^ES2600185", out$samples$lab_sample_id)))
  expect_true(all(grepl("^ES2600185", out$results$lab_sample_id)))
  expect_true(all(out$samples$sample_type == "Normal"))
})

test_that("SpreadsheetML: synthetic SX7654321 .XLS (ss:Index gaps, empty Data, row gap, QC sheet) parses identically to its .csv twin", {
  expect_twin_parse_identical(sx_csv, sx_xls)
})

test_that("SpreadsheetML: real .XLS output passes ir_validate()", {
  out <- parse_xtab(real_xls)
  expect_silent(sampleTidy:::ir_validate(out$results, kind = "results"))
  expect_silent(sampleTidy:::ir_validate(out$samples, kind = "samples"))
})

# ---- parse(): ss:Index / MergeAcross column placement --------------------------
#
# SX7654321 grid (1-based columns): labels col 4 (merged 4-5), samples in
# cols 6/7/8 = SX7654321001/002/003. Row 2's label is reached via a cell
# ss:Index="4" (col 3 omitted); row 4 skips cols 1-3 via ss:Index="4";
# row 14 (EC) omits CAS (col 2), the gap (col 5) and sample 002 (col 7) via
# ss:Index="3"/"6"/"8"; row 9 is omitted and row 10 carries ss:Index="10".

test_that("SpreadsheetML ss:Index: per-sample labels reached via cell ss:Index + MergeAcross land on the right sample columns", {
  out <- parse_xtab(sx_xls)
  s <- out$samples[order(out$samples$lab_sample_id), ]
  expect_identical(s$lab_sample_id, c("SX7654321001", "SX7654321002", "SX7654321003"))
  expect_identical(s$feature_raw, c("T.S01", "T.S02", "T.S03"))
  expect_identical(s$sample_datetime_raw, c("03/02/2026", "03/02/2026", "04/02/2026"))
  expect_identical(s$source_ref, c("r2c6", "r2c7", "r2c8"))
  expect_true(all(s$matrix_raw == "WATER"))
  expect_true(all(s$work_order == "SX7654321"))
  expect_true(all(s$sample_type == "Normal"))
})

test_that("SpreadsheetML ss:Index: a cell skipped by ss:Index is blank - EC sample 002 is skipped 'empty', 001/003 keep their own values", {
  out <- parse_xtab(sx_xls)
  ec <- out$results[grepl("^Electrical Conductivity", out$results$analyte_raw), ]
  ec <- ec[order(ec$lab_sample_id), ]
  expect_identical(ec$lab_sample_id, c("SX7654321001", "SX7654321003"))
  expect_identical(ec$value_raw, c("185", "600"))
  expect_identical(ec$source_ref, c("r14c6", "r14c8"))
  expect_true(all(is.na(ec$cas_number))) # CAS column omitted via ss:Index
  expect_true(all(ec$rl == 1))
  expect_true(all(ec$method_raw == "EA010P: Conductivity by PC Titrator"))

  sk <- out$report$skipped
  expect_identical(sk$reason[sk$source_ref == "r14c7"], "empty")
})

test_that("SpreadsheetML ss:Index: a Row ss:Index gap keeps file row numbering (source_ref) aligned with the .csv", {
  out <- parse_xtab(sx_xls)
  ph <- out$results[out$results$analyte_raw == "pH Value", ]
  ph <- ph[order(ph$lab_sample_id), ]
  expect_identical(ph$source_ref, c("r11c6", "r11c8"))
  expect_identical(ph$value_raw, c("6.40", "7.10"))
  expect_true(all(ph$method_raw == "EA005P: pH by PC Titrator"))
  expect_true(all(ph$units_raw == "pH Unit"))
  expect_true(all(ph$rl == 0.01))
  sk <- out$report$skipped
  expect_identical(sk$reason[sk$source_ref == "r11c7"], "not_computable") # "----"
})

test_that("SpreadsheetML: '<' non-detects (&lt; in the XML) and CAS/LOR are read as text, exactly as the .csv", {
  out <- parse_xtab(sx_xls)
  fl <- out$results[out$results$analyte_raw == "Fluoride", ]
  fl <- fl[order(fl$lab_sample_id), ]
  expect_identical(fl$value_raw, c("<0.1", "0.5", "<0.1"))
  expect_identical(fl$below_detection, c(TRUE, FALSE, TRUE))
  expect_true(all(fl$cas_number == "16984-48-8"))
  expect_true(all(fl$units_raw == "mg/L"))
  expect_true(all(fl$rl == 0.1))

  nox <- out$results[out$results$analyte_raw == "Nitrite + Nitrate as N", ]
  nox <- nox[order(nox$lab_sample_id), ]
  expect_identical(nox$value_raw, c("0.14", "<0.01", "0.38"))
  # "&amp;" in the method-group text decodes to a single "&"
  expect_true(all(nox$method_raw == "EK059G: Nitrite & Nitrate as N (NOx) by Discrete Analyser"))
})

# ---- parse(): encoding ----------------------------------------------------------
#
# The .XLS declares ISO-8859-1 and carries raw 0xB0 / 0xB5 bytes; the .csv
# twin carries U+FFFD that normalise_lab_text() repairs. Both must end as the
# same proper UTF-8 text.

test_that("SpreadsheetML encoding: ISO-8859-1 degree/micro bytes come out as U+00B0 / U+00B5 (real .XLS)", {
  out <- parse_xtab(real_xls)
  ec <- out$results[grepl("Conductivity", out$results$analyte_raw), ]
  expect_equal(nrow(ec), 2)
  expect_true(all(ec$analyte_raw == "Electrical Conductivity @ 25°C"))
  expect_true(all(ec$units_raw == "µS/cm"))
  expect_true(all(validUTF8(c(ec$analyte_raw, ec$units_raw))))
  # no replacement char, no shattered triple, no UTF-8-as-latin1 "Â"
  bad <- "�|ï¿½|Â"
  expect_false(any(grepl(bad, c(ec$analyte_raw, ec$units_raw))))
})

test_that("SpreadsheetML encoding: synthetic .XLS degree/micro match the .csv twin's repaired text", {
  from_xls <- parse_xtab(sx_xls)
  from_csv <- parse_xtab(sx_csv)
  ec_x <- from_xls$results[grepl("Conductivity", from_xls$results$analyte_raw), ]
  ec_c <- from_csv$results[grepl("Conductivity", from_csv$results$analyte_raw), ]
  expect_identical(unique(ec_x$analyte_raw), "Electrical Conductivity @ 25°C")
  expect_identical(unique(ec_x$units_raw), "µS/cm")
  expect_identical(unique(ec_x$analyte_raw), unique(ec_c$analyte_raw))
  expect_identical(unique(ec_x$units_raw), unique(ec_c$units_raw))
})

